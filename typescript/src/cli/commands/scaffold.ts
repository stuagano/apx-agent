/**
 * apx scaffold — generate a new agent project.
 *
 * TS port of the Python `_scaffold_apps` / `_scaffold_model_serving` flows.
 * Templates are inlined as static strings so the scaffold doesn't pull in
 * any runtime template engine — match the Python behavior exactly.
 *
 * Two `--target` modes:
 *
 *   * `model-serving` — flat agent.ts + app.ts layout. Deployed via the
 *     traditional Mosaic AI ChatAgent flow.
 *   * `apps` — Databricks Asset Bundle layout: `agent_server/` + `start.ts`
 *     entry running an Express server with `mountResponsesAgent`, plus
 *     `databricks.yml`. Deployed via `apx deploy --target apps`.
 */

