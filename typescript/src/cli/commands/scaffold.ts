// ---------------------------------------------------------------------------
// File-writing helpers
// ---------------------------------------------------------------------------

function sub(template: string, name: string): string {
  return template.replaceAll('<APP_NAME>', name);
}

/** Deps overridable by tests — defaults to real fs. */
export interface ScaffoldDeps {
  writeFile?: (path: string, content: string) => void;
  mkdir?: (path: string) => void;
  exists?: (path: string) => boolean;
  /** Optional logger; defaults to console.log. */
  log?: (msg: string) => void;
  /** Optional list-children — defaults to readdirSync. */
  readdir?: (path: string) => string[];
}

function defaultDeps(): Required<ScaffoldDeps> {
  return {
    writeFile: (path, content) => {
      mkdirSync(dirname(path), { recursive: true });
      writeFileSync(path, content);
    },
    mkdir: (path) => mkdirSync(path, { recursive: true }),
    exists: (path) => existsSync(path),
    log: (msg) => {
      // eslint-disable-next-line no-console
      console.log(msg);
    },
    readdir: (path) => readdirSync(path),
  };
}

function scaffoldModelServing(
  target: string,
  name: string,
  force: boolean,
  deps: Required<ScaffoldDeps>,
): void {
  const files: Record<string, string> = {
    'agent.ts': sub(MODEL_SERVING_AGENT_TS, name),
    'app.ts': sub(MODEL_SERVING_APP_TS, name),
    'package.json': sub(MODEL_SERVING_PACKAGE_JSON, name),
    'tsconfig.json': MODEL_SERVING_TSCONFIG,
    'README.md': sub(MODEL_SERVING_README, name),
  };
  writeAll(target, files, force, deps);
}

function scaffoldApps(
  target: string,
  name: string,
  force: boolean,
  deps: Required<ScaffoldDeps>,
): void {
  const files: Record<string, string> = {
    'package.json': sub(APPS_PACKAGE_JSON, name),
    'tsconfig.json': APPS_TSCONFIG,
    'databricks.yml': sub(APPS_DATABRICKS_YML, name),
    '.env.example': APPS_ENV_EXAMPLE,
    '.gitignore': APPS_GITIGNORE,
    'README.md': sub(APPS_README, name),
    'agent_server/agent.ts': sub(APPS_AGENT_TS, name),
    'agent_server/index.ts': sub(APPS_INDEX_TS, name),
    'agent_server/start.ts': sub(APPS_START_TS, name),
  };
  writeAll(target, files, force, deps);
}

function writeAll(
  target: string,
  files: Record<string, string>,
  force: boolean,
  deps: Required<ScaffoldDeps>,
): void {
  for (const [rel, content] of Object.entries(files)) {
    const path = join(target, rel);
    if (deps.exists(path) && !force) {
      deps.log(`  skip   ${path} (exists; pass --force to overwrite)`);
      continue;
    }
    deps.writeFile(path, content);
    deps.log(`  write  ${path}`);
  }
}

// ---------------------------------------------------------------------------
// Commander registration
// ---------------------------------------------------------------------------

// The project name is substituted into databricks.yml (bundle/resource name)
// and package.json ("name"), and used as a directory segment. Restrict it to a
// safe charset so the generated files stay valid and the path cannot escape the
// target dir. Must start alphanumeric; allows hyphen/underscore/dot internally;
// rejects path separators (M/L14 — robustness, not a security boundary).
const PROJECT_NAME_RE = /^[A-Za-z0-9](?:[A-Za-z0-9._-]*[A-Za-z0-9])?$/;

const ScaffoldOptionsSchema = z.object({
  name: z
    .string()
    .min(1, 'project name is required')
    .regex(
      PROJECT_NAME_RE,
      'project name must start and end with a letter or digit and contain only letters, digits, hyphens, underscores, or dots (no path separators)',
    ),
  dir: z.string().min(1).default('.'),
  target: z.enum(['model-serving', 'apps']).default('model-serving'),
  force: z.boolean().default(false),
});

export interface ScaffoldCommandDeps extends ScaffoldDeps {}

export function registerScaffoldCommand(
  program: Command,
  deps: ScaffoldCommandDeps = {},
): void {
  const resolved = { ...defaultDeps(), ...deps };

  program
    .command('scaffold <name>')
    .description('Generate a new agent project at <name>.')
    .option(
      '--dir <directory>',
      'Target directory. Default: current directory.',
      '.',
    )
    .option(
      '--target <target>',
      "Deployment target ('model-serving' or 'apps'). Default: model-serving.",
      'model-serving',
    )
    .option('--force', 'Overwrite existing files.', false)
    .action(
      async (
        name: string,
        rawOpts: { dir?: string; target?: string; force?: boolean },
      ) => {
        const opts = ScaffoldOptionsSchema.parse({
          name,
          dir: rawOpts.dir,
          target: rawOpts.target,
          force: Boolean(rawOpts.force),
        });
        const target = resolve(opts.dir, opts.name);

        if (resolved.exists(target) && !opts.force) {
          let children: string[] = [];
          try {
            children = resolved.readdir(target);
          } catch {
            children = [];
          }
          if (children.length > 0) {
            throw new Error(
              `${target} already exists and is not empty. Pass --force to overwrite.`,
            );
          }
        }
        resolved.mkdir(target);

        if (opts.target === 'apps') {
          scaffoldApps(target, opts.name, opts.force, resolved);
        } else {
          scaffoldModelServing(target, opts.name, opts.force, resolved);
        }
        resolved.log('');
        resolved.log(`Scaffolded ${opts.name} at ${target} (target=${opts.target}).`);
        if (opts.target === 'apps') {
          resolved.log(`Next: cd ${opts.name} && npm install && npm run dev`);
        } else {
          resolved.log(`Next: cd ${opts.name} && npm install && npm run build`);
        }
      },
    );
}
