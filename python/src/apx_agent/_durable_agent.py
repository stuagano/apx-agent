def durable_request_headers(auth: Any, *, principal: str, forward: bool) -> Any:
    """Per-request headers for the compiled graph; never carries the token itself.

    ``forward`` must already account for the SDK's local verdict and whether the
    agent has delegates. The resolver asks the SDK's request-user client at call
    time, so a closed context fails closed.
    """
    from ._defaults import DatabricksAppsHeaders

    return DatabricksAppsHeaders(
        host=None, user_name=None, user_id=principal, user_email=None, request_id=None, token=None,
        auth_headers=(lambda: auth.client_for("user").config.authenticate()) if forward else None,
    )


def build_native_manifest(
    *,
    config: AgentConfig,
    authorization_plan: AuthorizationPlan,
    agent: BaseAgent,
) -> str:
    """Compile the existing authorization plan into AgentKit's native contract.

    A managed session is written only when the agent can bind it. Composite
    agents (anything other than ``LlmAgent``) drop the auto-attached durable
    session the same way ``inspect_target`` does, so the staged ``agent.toml``
    does not declare a store the runtime will never use. An explicit
    ``session_store=`` on a composite is still rejected by ``inspect_target``.
    """
    from databricks_agentkit.runtime.tool_manifest import parse_user_auth
    from ._agent_toml import needs_request_user
    from ._project_gen import _write_toml_section
    from ._runtime_targets import inspect_target

    required = needs_request_user(authorization_plan, config)
    scopes = list(authorization_plan.user_api_scopes) if required else []
    auth = {"required": required, "additional_api_scopes": scopes}
    parse_user_auth({"auth": {"user": auth}})
    if config.recovery and required:
        raise ValueError("Request-user recovery is unsupported")
    # Same LlmAgent-only session rule as inspect_target: a composite drops the
    # durable target's auto-attached store instead of shipping it unused.
    session_store = inspect_target(agent, config=config, target=config.target).session_store
    lines = ["# Generated by APX from agent declarations; do not edit.", "schema_version = 1", ""]
    _write_toml_section(lines, "agent", {"framework": "langgraph", "server": "agentbricks"})
    _write_toml_section(lines, "auth.user", auth)
    if config.memory is not None and config.memory.type == "managed":
        _write_toml_section(lines, "memory_store", {"name": config.memory.store_name})
    if session_store is not None:
        _write_toml_section(lines, "session_store", {"name": session_store})
    return "\n".join(lines)


def _durable_discovery_config() -> AgentConfig | None:
    """The cwd agent config, validated as the target this compiler just built.

    ``compile_to_durable_agent_server`` does not receive the caller's config, and
    protocol setup rediscovers ``[tool.apx.agent]`` from the working directory.
    Doctor and other callers override ``target`` to ``durable_agent_server``
    without rewriting the file. Reloading that file at its declared target
    rejects ``deploy.space`` / ``backend='apps_api'``, which are legal only on
    this target. A missing file stays ``None`` so setup can return early.
    """
    from ._inspection import _agent_config_fields, _resolve_agent_pyproject
    from ._models import AgentConfig

    resolved = _resolve_agent_pyproject(("tool", "apx", "agent"), None)
    if resolved is None or not resolved.exists():
        return None
    fields = _agent_config_fields(resolved, ("tool", "apx", "agent"))
    if fields is None:
        return None
    return AgentConfig.model_validate({**fields, "target": "durable_agent_server"})


# The current turn's RequestAuthContext. Genie tools are built once at startup,
# so their identity resolver reads the request from here at call time.
_REQUEST_AUTH: contextvars.ContextVar[Any] = contextvars.ContextVar("apx_platform_request_auth")


def platform_client_for(service_ws: Any) -> ClientFor:
    """agent.toml identity resolver: ``app`` is the service client; ``user`` is
    the current request's user and never falls back to the service client."""

    def client_for(mode: str) -> Any:
        if mode == "app":
            return service_ws
        auth = _REQUEST_AUTH.get(None)
        if auth is None:
            from databricks_agentkit.runtime.auth import AuthError

            # AgentKit's MCP resolver attaches the integration id (mcp_auth_error).
            raise AuthError("MCP_USER_AUTHORIZATION_MISSING",
                            "This deployed MCP integration requires request-user authorization.")
        return auth.client_for("user")

    return client_for


@dataclass(frozen=True)
class DurableHandlers:
    invoke: Callable[[Any, Any], Awaitable[dict[str, Any]]]


def _pending(graph: Any, config: dict[str, Any] | None) -> Any | None:
    if config is None:
        return None
    interrupts = graph.get_state(config).interrupts
    return interrupts[0].value if interrupts else None


def compile_durable_handlers(
    agent: BaseAgent,
    *,
    model: str,
    service_ws: Any,
    checkpointer: Any | None = None,
    require_user: bool = False,
    recovery: bool = False,
    project_root: Path | None = None,
    platform_tools: dict[str, list[Any]] | None = None,
) -> DurableHandlers:
    """Build native message handlers; no MLflow request/response dependency.

    The SDK owns transient request-user credentials and session namespacing.
    The service client never fills a user slot.
    Recovery is opt-in and resumes invocation-tagged managed checkpoints.
    ``platform_tools`` are the startup-built agent.toml tools; user-auth MCP
    tools are fetched from ``project_root``'s agent.toml inside each request.
    """
    if service_ws is None:
        raise ValueError("durable_agent_server requires an explicit service_ws runtime binding")
    from ._runtime_targets import RuntimeRequirements, inspect_target

    report = inspect_target(agent, target="durable_agent_server", checkpointer=checkpointer,
                            requirements=RuntimeRequirements(recovery=recovery, user_identity=require_user))
    report.require_compatible()
    require_user = require_user or report.user_identity_required
    if checkpointer is not None and not isinstance(agent, LlmAgent):
        raise ValueError("Checkpoint sessions currently require LlmAgent")

    from ._resources import _iter_sub_agents, _iter_tool_fns

    # Declared sub_agents (materialized after compile) or hand-wired delegates:
    # only then does any outbound call need request-user auth resolved.
    has_delegates = bool(list(_iter_sub_agents(agent))) or any(
        hasattr(fn, "__apx_sub_agent_url__") for fn in _iter_tool_fns(agent))
    static = dict(platform_tools) if platform_tools else {}
    refs = [ref for _, ref in platform_tool_leaves(agent)]
    if refs and project_root is None:
        raise ValueError("platform_tools() needs an agent.toml in the project root (project_root=None)")
    request_ids = frozenset() if any(not r.ids for r in refs) else frozenset().union(*(r.ids for r in refs))
    client_for = platform_client_for(service_ws)

    def request_auth(context: Any) -> Any:
        """The one validation site for a context's recovery and auth contract.

        Runs before anything credentialed (request MCP fetch, graph turn).
        """
        if bool(getattr(context, "is_recovery", False)) and not recovery:
            raise ValueError("recovery is not wired for durable_agent_server")
        if recovery and (not isinstance(getattr(context, "invocation_id", None), str) or not context.invocation_id):
            raise ValueError("recovery requires a non-empty invocation_id")
        from databricks_agentkit.runtime.auth import RequestAuthContext
        auth = getattr(context, "request_auth", None)
        if recovery and auth is not None:
            raise ValueError("Request-user recovery is unsupported")
        if (require_user and auth is None) or (auth is not None and not isinstance(auth, RequestAuthContext)):
            raise ValueError("user_identity requires the SDK's active RequestAuthContext")
        return auth

    def execute(value: Any, context: Any, auth: Any, emit_message: Callable[[Any], None] | None,
                platform: dict[str, list[Any]]) -> dict[str, Any]:
        recovering = bool(getattr(context, "is_recovery", False))
        user_ws = auth.client_for("user") if auth is not None else None
        headers = None
        if auth is not None and user_ws is not None:
            principal = user_ws.current_user.me().id
            if not isinstance(principal, str) or not principal:
                raise ValueError("user_identity could not resolve the authenticated principal")
            # The SDK's per-request verdict is authoritative: a local context's
            # "user" client is the developer/app credential, never forward it.
            forward = has_delegates and not auth._local
            headers = durable_request_headers(auth, principal=principal, forward=forward)
        if isinstance(value, list):
            value = {"messages": value}
        if not isinstance(value, dict) or set(value) - {"messages", "resume"}:
            raise ValueError("Native input must contain messages and optional resume; session_id belongs in the top-level invocation envelope")
        messages = value.get("messages", [])
        if not isinstance(messages, list):
            raise ValueError("messages must be a list")
        # Durable invocation input is fresh chat input. Tool results and state
        # are produced by execution/checkpoints, never supplied by a caller.
        for message in messages:
            if not isinstance(message, dict) or set(message) - {"role", "content"}:
                raise ValueError("Each message must contain only role and content")
            if message.get("role") != "user" or not isinstance(message.get("content"), str):
                raise ValueError("Native input accepts user text messages only")
        resume = value.get("resume")
        if resume is not None and checkpointer is None:
            raise ValueError("Approval resume requires a checkpointed session")
        config = None
        if checkpointer is not None:
            session = context.session_id
            if not isinstance(session, str) or not session:
                raise ValueError("A checkpointed invocation requires a non-empty session_id")
            scope = [getattr(agent, "_name", None), session]
            if headers is not None:
                scope.insert(1, headers.user_id)
            key = hashlib.sha256(json.dumps(scope).encode()).hexdigest()
            config = {"configurable": {"thread_id": key, "actor_id": key}}
        from langchain_core.messages import HumanMessage

        graph = compile_to_langgraph(
            agent, ws=user_ws, service_ws=service_ws, model=model, headers=headers,
            **({"checkpointer": checkpointer} if checkpointer is not None else {}),
            platform_tools=platform,
        )
        turn = run_graph_turn(
            graph, agent, [HumanMessage(content=m["content"]) for m in messages],
            config=config, resume=resume, read_interrupt=_pending,
            emit_message=emit_message,
            invocation_id=context.invocation_id if recovery else None,
            recovery=recovering,
        )
        if turn.approval_required is not None:
            return {"status": "interrupted", "messages": [], "approval_required": turn.approval_required}
        return {"status": "completed", "messages": [m.model_dump(mode="json") for m in turn.messages]}

    async def invoke(value: Any, context: Any) -> dict[str, Any]:
        loop = asyncio.get_running_loop()

        def emit_message(message: Any) -> None:
            # Native SDK persists and orders these events for SSE replay. Wait
            # for each write: a slow store must exert backpressure on generation.
            event = {"type": "agent.message.delta", "message": message.model_dump(mode="json")}
            asyncio.run_coroutine_threadsafe(context.emit(event), loop).result()

        # Sync graph/checkpoint tools run outside the server's event loop.
        can_emit = callable(getattr(context, "emit", None))
        auth = request_auth(context)
        # to_thread copies this context, so tools in the turn see the request.
        token = _REQUEST_AUTH.set(auth)
        try:
            platform = dict(static)
            if project_root is not None and refs:
                from ._platform_tools import request_platform_tools

                platform.update(await request_platform_tools(project_root, client_for, request_ids))
            result = await asyncio.to_thread(
                execute, value, context, auth,
                emit_message if can_emit and not report.streaming_buffered else None,
                platform,
            )
        finally:
            _REQUEST_AUTH.reset(token)
        if can_emit and report.streaming_buffered and result["status"] == "completed" and result["messages"]:
            # Only publish the final validated answer, never buffered intermediate
            # model/tool messages that the output checks did not approve.
            await context.emit({"type": "agent.message.completed", "message": result["messages"][-1]})
        return result

    return DurableHandlers(invoke=invoke)


def compile_to_durable_agent_server(
    agent: BaseAgent,
    *,
    model: str,
    service_ws: Any,
    checkpointer: Any | None = None,
    session_store: str | None = None,
    require_user: bool = False,
    recovery: bool = False,
    project_root: Path | None = None,
) -> Any:
    """Create the optional SDK server without importing ResponsesAgent.

    ``project_root`` holds the agent.toml that ``platform_tools()`` references
    resolve against; an agent with references and no agent.toml does not compile.
    """
    from ._runtime_targets import RuntimeRequirements, inspect_target

    inspect_target(agent, target="durable_agent_server", checkpointer=checkpointer,
                   session_store=session_store,
                   requirements=RuntimeRequirements(recovery=recovery, user_identity=require_user)).require_compatible()
    try:
        from databricks_agentkit.runtime.app import DurableAgentServer
    except ImportError as exc:
        raise ImportError("durable_agent_server requires the optional SDK; install apx-agent[agentbricks] in the host project") from exc
    if session_store is not None:
        if service_ws is None:
            raise ValueError("session_store requires an explicit service_ws runtime binding")
        from databricks_agentkit.langgraph.session_store import DatabricksSessionStoreSaver

        checkpointer = DatabricksSessionStoreSaver(session_store, workspace_client=service_ws)
    from databricks_agentkit.runtime.auth import InvocationAuthPolicy

    report = inspect_target(agent, target="durable_agent_server", checkpointer=checkpointer)
    policy = InvocationAuthPolicy.from_manifest(allow_missing=True)
    if require_user or report.user_identity_required:
        policy = replace(policy, user_required=True)
    if recovery and policy.requires_user:
        raise ValueError("recovery is incompatible with the manifest's request-user authentication")
    startup = _startup_platform_tools(agent, project_root, model=model, service_ws=service_ws)
    handlers = compile_durable_handlers(agent, model=model, service_ws=service_ws,
                                        checkpointer=checkpointer, require_user=policy.requires_user, recovery=recovery,
                                        project_root=project_root, platform_tools=startup.tools)
    app = DurableAgentServer(auth_policy=policy)
    # Per-id startup materialization failures, for offline doctor (by id, not message).
    app.state.apx_platform_tool_failures = startup.failures
    app.invoke(handlers.invoke)
    if recovery:
        app.recover(handlers.invoke)

    from ._resources import _iter_sub_agents
    from ._wiring import mount_durable_protocol

    # Discovery only. DurableAgentServer already owns /api/invocations and its
    # auth policy; this does not mount the root chat UI or /_apx/*. setup_agent
    # fetches remote tools when a config exists, so this does not fetch again.
    # The compiler does not receive the caller's AgentConfig; cwd discovery must
    # still validate as this target, or a space/apps_api declaration (legal only
    # with durable_agent_server) fails during lifespan startup.
    discovery = _durable_discovery_config()
    mount_durable_protocol(app, agent, config=discovery)
    # setup_agent fetches remotes when a config exists. With no config it returns
    # before that fetch, so the card materialization (#436) still has to run.
    if discovery is None and list(_iter_sub_agents(agent)):
        from ._wiring import _chain_lifespan

        async def _materialize_sub_agents() -> None:
            await agent.fetch_remote_tools()

        _chain_lifespan(app, _materialize_sub_agents)

    @app.get("/readyz")
    async def readyz() -> Any:
        import uuid
        from fastapi.responses import JSONResponse

        try:
            await app._runtime.runtime_store.get(invocation_id=str(uuid.uuid4()))
        except Exception:
            return JSONResponse(status_code=503, content={
                "status": "degraded", "checks": {"runtime_store": "unreachable"},
            })
        if startup.error is not None:
            return JSONResponse(status_code=503, content={
                "status": "degraded", "checks": {"platform_tools": startup.error},
            })
        return {"status": "ready", "checks": {
            "runtime_store": "ok", "durable": app._runtime.is_durable,
            "agent_execution": "not_probed",
        }}

    return app


@dataclass(frozen=True)
class _StartupPlatformTools:
    tools: dict[str, list[Any]]
    error: str | None
    failures: dict[str, str]


def _startup_platform_tools(agent: BaseAgent, project_root: Path | None, *, model: str,
                            service_ws: Any) -> _StartupPlatformTools:
    """Build the startup agent.toml tools. Declaration errors fail the compile;
    materialization errors (network, auth) degrade ``/readyz`` instead."""
    if not platform_tool_leaves(agent):
        return _StartupPlatformTools({}, None, {})
    from ._agent_toml import check_agent_toml, load_agent_toml
    from ._apps_authorization import compile_authorization_plan
    from ._doctor import Status
    from ._platform_tools import static_platform_tools

    if project_root is None or load_agent_toml(project_root) is None:
        raise ValueError(f"platform_tools() needs an agent.toml in the project root ({project_root})")
    plan = compile_authorization_plan(agent, model=model)
    fails = [c for c in check_agent_toml(project_root, agent, plan, None, runtime_only=True)
             if c.status == Status.FAIL]
    if fails:
        raise ValueError("; ".join(f"{c.detail} — {c.fix}" for c in fails))
    try:
        built = static_platform_tools(project_root, platform_client_for(service_ws))
    except Exception as exc:  # surfaced on /readyz, never swallowed
        return _StartupPlatformTools({}, f"{type(exc).__name__}: {exc}", {})
    failed = "; ".join(f"{i}: {error}" for i, error in built.failures.items())
    return _StartupPlatformTools(built.tools, failed or None, dict(built.failures))
