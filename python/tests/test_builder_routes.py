def test_state_reports_identity_from_pyproject(tmp_path, monkeypatch, app):
    """Identity (name + profile) is sourced from [tool.apx.agent] in pyproject.toml."""
    monkeypatch.chdir(tmp_path)
    (tmp_path / "pyproject.toml").write_text(
        '[project]\nname = "demo"\nversion = "0.1.0"\n'
        '[tool.apx.agent]\nname = "mcp-demo-agent"\nprofile = "fe-stable"\n'
    )
    client = TestClient(app)
    r = client.get("/_apx/builder/state")
    assert r.status_code == 200, r.text
    body = r.json()
    assert body["identity"]["name"] == "mcp-demo-agent"
    assert body["identity"]["profile"] == "fe-stable"


