def test_state_reports_drift_when_agent_py_newer(tmp_path, monkeypatch, app):
    """If agent.py mtime > sidecar mtime, state returns drift=True."""
    monkeypatch.chdir(tmp_path)
    import time
    (tmp_path / ".apx-builder.json").write_text('{"nodes":[],"edges":[]}')
    time.sleep(0.05)  # ensure mtime gap
    (tmp_path / "agent.py").write_text("# Generated by apx-agent visual builder\nfrom apx_agent import Agent\n")
    client = TestClient(app)
    r = client.get("/_apx/builder/state")
    assert r.status_code == 200, r.text
    body = r.json()
    assert body["drift"] is True
    assert body["agent_py_exists"] is True
    assert body["sidecar_exists"] is True


